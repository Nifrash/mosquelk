from django import forms
from django.core.exceptions import ValidationError
from django.utils.translation import gettext_lazy as _


class ContactForm(forms.Form):
    """
    Public contact form with server-side validation and basic bot protection.

    Security notes:
    - `website` is a honeypot. Normal visitors never see or fill it.
    - `form_token` is a signed/time-checked token validated by the view.
    - All meaningful validation is performed server-side.
    """

    name = forms.CharField(
        min_length=2,
        max_length=120,
        label=_("Name"),
        widget=forms.TextInput(
            attrs={
                "class": "form-control",
                "placeholder": _("Your name"),
                "autocomplete": "name",
                "maxlength": "120",
            }
        ),
    )

    email = forms.EmailField(
        max_length=254,
        label=_("Email"),
        widget=forms.EmailInput(
            attrs={
                "class": "form-control",
                "placeholder": _("Email address"),
                "autocomplete": "email",
                "maxlength": "254",
            }
        ),
    )

    subject = forms.CharField(
        min_length=4,
        max_length=160,
        label=_("Subject"),
        widget=forms.TextInput(
            attrs={
                "class": "form-control",
                "placeholder": _("How can we help?"),
                "maxlength": "160",
            }
        ),
    )

    message = forms.CharField(
        min_length=10,
        max_length=5000,
        label=_("Message"),
        widget=forms.Textarea(
            attrs={
                "class": "form-control",
                "rows": 7,
                "placeholder": _("Write your message here"),
                "maxlength": "5000",
            }
        ),
    )

    # Honeypot field. It is intentionally named like a normal web field.
    website = forms.CharField(
        required=False,
        label="",
        widget=forms.TextInput(
            attrs={
                "class": "contact-form-honeypot-input",
                "tabindex": "-1",
                "autocomplete": "off",
                "aria-hidden": "true",
            }
        ),
    )

    # Signed token generated by the view.
    form_token = forms.CharField(
        required=True,
        widget=forms.HiddenInput(),
    )

    @staticmethod
    def _reject_header_characters(value, field_label):
        if "\r" in value or "\n" in value:
            raise ValidationError(
                _("%(field)s contains invalid characters."),
                params={"field": field_label},
            )
        return value

    def clean_name(self):
        value = self.cleaned_data["name"].strip()
        return self._reject_header_characters(
            value,
            _("Name"),
        )

    def clean_subject(self):
        value = self.cleaned_data["subject"].strip()
        return self._reject_header_characters(
            value,
            _("Subject"),
        )

    def clean_message(self):
        value = self.cleaned_data["message"].strip()

        if not value:
            raise ValidationError(
                _("Please enter your message.")
            )

        return value

    def clean(self):
        cleaned_data = super().clean()

        # Normal visitors never fill this hidden field.
        if cleaned_data.get("website"):
            raise ValidationError(
                _("We could not submit this form. Please refresh the page and try again.")
            )

        return cleaned_data
